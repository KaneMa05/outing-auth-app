const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { CURRICULUM_WORKBOOK_DAY_COUNTS } = require("./curriculum-workbook-days");

const root = path.resolve(__dirname, "..");
const appSource = fs.readFileSync(path.join(root, "app.js"), "utf8");
const dataSource = fs.readFileSync(path.join(root, "curriculum-data.js"), "utf8");
const subjectMatch = appSource.match(/const CURRICULUM_QUEST_SUBJECTS = (\[[\s\S]*?\n\]);\nlet curriculumQuestSelectedSubjectId/);
if (!subjectMatch) throw new Error("CURRICULUM_QUEST_SUBJECTS not found");

const subjectSandbox = { result: null };
vm.runInNewContext(`result = ${subjectMatch[1]}`, subjectSandbox);
const dataSandbox = { window: {} };
vm.runInNewContext(dataSource, dataSandbox);
const subjects = subjectSandbox.result;
const lecturesBySubject = dataSandbox.window.CURRICULUM_QUEST_LECTURES;

const quote = (value) => `'${String(value ?? "").replace(/'/g, "''")}'`;
const textArray = (values) => `array[${values.map(quote).join(", ")}]::text[]`;
const subjectRows = [];
const stageRows = [];
const lectureRows = [];
const trackTargetsBySubject = {
  "criminal-law": ["경찰직 - 공채(순경)", "경찰직 - 해경학과 항해(경장)", "경찰직 - 해경학과 기관(경장)"],
  "coast-guard-intro": ["경찰직 - 공채(순경)", "경찰직 - 함정요원 항해(순경)", "경찰직 - 함정요원 기관(순경)", "경찰직 - 해경학과 항해(경장)", "경찰직 - 해경학과 기관(경장)"],
  "maritime-law": ["경찰직 - 공채(순경)", "경찰직 - 함정요원 항해(순경)", "경찰직 - 함정요원 기관(순경)"],
};
const sortOrderBySubject = { "criminal-law": 1, "coast-guard-intro": 3, "maritime-law": 4 };

subjects.forEach((subject, subjectIndex) => {
  const expectedDayCounts = CURRICULUM_WORKBOOK_DAY_COUNTS[subject.id];
  const actualDayCounts = subject.stageTitles.map((_, stageIndex) =>
    (lecturesBySubject?.[subject.id]?.[String(stageIndex + 1)] || []).length
  );
  if (!expectedDayCounts || JSON.stringify(actualDayCounts) !== JSON.stringify(expectedDayCounts)) {
    throw new Error(`${subject.id}: 앱 강의 묶음이 엑셀 비고 일차와 일치하지 않습니다.`);
  }
  subjectRows.push(`(${quote(subject.id)}, ${quote(subject.name)}, ${quote(subject.shortName)}, ${quote(subject.tone)}, ${textArray(trackTargetsBySubject[subject.id] || ["경찰직 - 공채(순경)"])}, ${sortOrderBySubject[subject.id] || subjectIndex + 1}, true, false)`);
  subject.stageTitles.forEach((title, stageIndex) => {
    const stageNumber = stageIndex + 1;
    const stageId = `${subject.id}-stage-${stageNumber}`;
    const lectures = lecturesBySubject?.[subject.id]?.[String(stageNumber)] || [];
    const stageTitle = lectures.map((lecture) => String(lecture.title || "").trim()).filter(Boolean).join(", ") || title;
    const firstTitle = String(lectures[0]?.title || "").trim();
    const requiresWrapUp = !/^(?:전과목)?OT(?:-|$)/i.test(firstTitle);
    stageRows.push(`(${quote(stageId)}, ${quote(subject.id)}, ${stageNumber}, ${quote(stageTitle)}, ${stageNumber}, true, ${requiresWrapUp})`);
    lectures.forEach((lecture, lectureIndex) => {
      lectureRows.push(`(${quote(`${stageId}-lecture-${lectureIndex + 1}`)}, ${quote(stageId)}, ${quote(lecture.no)}, ${quote(lecture.title)}, ${lectureIndex + 1})`);
    });
  });
});

const sql = `-- Generated by scripts/generate-curriculum-seed.js. Do not edit manually.
begin;

insert into public.curriculum_subjects
  (id, name, short_name, tone, target_tracks, sort_order, is_published, is_archived)
values
  ${subjectRows.join(",\n  ")}
on conflict (id) do update set
  name = excluded.name,
  short_name = excluded.short_name,
  tone = excluded.tone,
  target_tracks = excluded.target_tracks,
  sort_order = excluded.sort_order,
  is_published = excluded.is_published,
  is_archived = excluded.is_archived,
  updated_at = now();

insert into public.curriculum_stages
  (id, subject_id, stage_number, title, sort_order, is_published, requires_wrap_up)
values
  ${stageRows.join(",\n  ")}
on conflict (id) do update set
  subject_id = excluded.subject_id,
  stage_number = excluded.stage_number,
  title = excluded.title,
  sort_order = excluded.sort_order,
  is_published = excluded.is_published,
  requires_wrap_up = excluded.requires_wrap_up,
  updated_at = now();

insert into public.curriculum_lectures
  (id, stage_id, lecture_number, title, sort_order)
values
  ${lectureRows.join(",\n  ")}
on conflict (id) do update set
  stage_id = excluded.stage_id,
  lecture_number = excluded.lecture_number,
  title = excluded.title,
  sort_order = excluded.sort_order,
  updated_at = now();

commit;
`;

fs.writeFileSync(path.join(root, "supabase", "seed-curriculum-public-recruitment.sql"), sql);
console.log(`Generated ${subjects.length} subjects, ${stageRows.length} stages, ${lectureRows.length} lectures.`);
