// Rebuild the local playground with the current production renderer, without booting the app.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const target = path.join(root, 'docs/study-character-progression/playground');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const shared = fs.readFileSync(path.join(root, 'shared.js'), 'utf8');
function extract(source, name) {
  const start = source.indexOf(`function ${name}(`);
  if (start < 0) throw new Error(`Missing renderer: ${name}`);
  const rest = source.slice(start);
  const end = rest.search(/\n(?:async )?function /);
  return end < 0 ? rest : rest.slice(0, end);
}
const names = ['renderStudyCafeAvatar','renderStudyCafeHair','renderStudyCafeSeatedVisual','renderStudyCafeChairBack','renderStudyCafeWritingArms','getStudyCafePublicEquipmentClass','renderStudyCafePublicCosmetics','isStudyCafeFireEnabled','getStudyCafeFireSeconds','renderStudyCafeFire','updateStudyCafeFireNode','renderStudyCafeFireProgress','updateStudyCafeFireProgress','updateStudyCafeFireStages','formatStudyBusinessDateKey'];
fs.mkdirSync(target, { recursive: true });
fs.writeFileSync(path.join(target, 'renderer.js'), '// Generated by scripts/build-study-fire-playground.cjs from current app.js/shared.js.\n' + extract(shared, 'el') + '\n' + names.map(n => extract(app, n)).join('\n'));
console.log('Ready: http://localhost:3000/docs/study-character-progression/playground/index.html');
